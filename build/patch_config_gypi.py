#!/usr/bin/env python3
"""Make the shared-libuv link flags apply to the target toolset only.

configure.py puts `-L<uv path>` and `-luv` in the global target_defaults, so
every host-toolset executable (node_js2c, torque, bytecode_builtins_list_
generator, ...) tries to link the ARM libuv and fails.  Move `libraries`
under a `_toolset=="target"` condition so only QNX binaries link it.

config.gypi is regenerated by configure.py, so run this after configure.
"""
import json

P = "/root/nodebuild/node-v24.22.1/config.gypi"

txt = open(P, encoding="utf-8").read()
i = txt.index("{")
prefix, body = txt[:i], txt[i:]
data = json.loads(body)

td = data["target_defaults"]
libs = td.get("libraries")
if not libs:
    print("no target_defaults libraries; nothing to do")
    raise SystemExit(0)

# Already moved?
for cond in td.get("conditions", []):
    if isinstance(cond, list) and cond and cond[0] == "_toolset=='target'" \
            and "libraries" in cond[1]:
        print("already patched")
        raise SystemExit(0)

td.pop("libraries")
td.setdefault("conditions", []).append(
    ["_toolset=='target'", {"libraries": libs}])

open(P, "w", encoding="utf-8").write(
    prefix + json.dumps(data, indent=2) + "\n")
print("config.gypi patched: libraries are target-toolset only")
